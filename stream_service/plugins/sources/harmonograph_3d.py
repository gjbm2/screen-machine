"""Harmonograph 3D: glowing 3D Lissajous / harmonograph curves woven like a laser sculpture.

Source: Original (inspired by https://en.wikipedia.org/wiki/Harmonograph and https://en.wikipedia.org/wiki/Lissajous_curve)
Author: smfx (original; harmonograph and Lissajous maths)
License: MIT (original)
license_class: permissive

Written from scratch from the textbook harmonograph formula: each axis is a sum of two damped sinusoids,
    x(s) = A_x * (e^{k s} sin(2 pi (f1_x s + phi1_x)) + c2 e^{1.7 k s} sin(2 pi (f2_x s + phi2_x))) / (1 + c2)
(likewise y, z), with the curve parameter s running from -trail (the faded tail) to 0 (the comet head).
  * f1 comes from a curated ratio table (3:2:1 -> 4:3:1 -> 4:3:2 -> 5:3:2 -> 5:4:3), morphed continuously with a
    short dwell on each pure figure; f2 is the next axis's ratio (the rotary-pendulum coupling), weighted by
    ``complexity``.  A slow frequency wobble adds the harmonograph's "detuning".
  * The comet trace: every phase is host-integrated, phi += f * trace_rate * dt (wrapped), so the whole curve
    slides along itself and the head traces the figure; per-curve detune drifts (seeded) make the nested curves
    precess against each other and weave.  ``damping`` is the exponential decay along the tail, so the tail
    spirals into the centre like a real harmonograph trace.
  * Up to 8 concentric curves (``curve_count`` fades the next one in continuously) of 4096 vertices each are
    generated by one small kernel into polyline + ribbon-rail buffers, then drawn with splat3d: a hot core
    polyline, a ruled ribbon/tube (camera-facing frame, so twist 0 reads as a luminous tube and twist > 0 as a
    twisting ribbon that turns edge-on and back), and bright comet heads with a soft halo.  Depth fade at the
    back, bloom + wide halo, ACES, a dim palette-tinted background.

Macros: energy -> trace speed, detune rate, rotation rate, curve-count weights, brightness, bloom and camera
orbit.  pulse -> line / ribbon width kick, brightness kick (<= ~40%) and a comet-head flare.  speed scales the trace,
detune and rotation rates; drift moves the palette along the curve parameter; intensity is exposure.
"""
from __future__ import annotations

import math

import numpy as np

from stream_service.gpu import raw_module
from stream_service.plugins.base import Source

from stream_service.plugins._lib.cuda import launch_2d
from stream_service.plugins._lib.palettes import PALETTES
from stream_service.plugins._lib.params import num, standard_scene_params
from stream_service.plugins._lib.splat3d import Splat3D, look_at, mat_euler, orbit
from stream_service.plugins._lib.upsample import internal_size

M_MAX = 8            # curves
K = 4096             # vertices per curve
NPC = 20             # floats per curve in the param buffer
NG = 16              # global params
RATIOS = np.array([(3, 2, 1), (4, 3, 1), (4, 3, 2), (5, 3, 2), (5, 4, 3)], np.float64)
AMP = (1.35, 1.08, 1.35)
CAM_D = 4.7

_SRC = r"""
#define TAU 6.28318530718f
__device__ __forceinline__ float3 h_cross(float3 a, float3 b) {
    return make_float3(a.y * b.z - a.z * b.y, a.z * b.x - a.x * b.z, a.x * b.y - a.y * b.x);
}
__device__ __forceinline__ float h_len(float3 a) { return sqrtf(a.x * a.x + a.y * a.y + a.z * a.z); }

// one thread per (vertex k, curve m).  cpar: NPC floats per curve:
//   0-2 phi1, 3-5 phi2, 6-8 f1, 9-11 f2, 12 scale, 13 weight, 14 palette offset, 15 twist phase
// g: 0 span, 1 damping k, 2 c2, 3-5 amp, 6 ribbon half width, 7-9 eye (model space), 10 twist turns/s-unit,
//    11 head boost, 12 tail floor, 13 head sharpness, 14 palette span along the curve
extern "C" __global__ void harmo_gen(float4* __restrict__ C, float4* __restrict__ RA, float4* __restrict__ RB,
                                     float* __restrict__ IDX, float4* __restrict__ HEAD, float* __restrict__ HIDX,
                                     const float* __restrict__ cpar, const float* __restrict__ g,
                                     const int K, const int M)
{
    const int k = blockIdx.x * blockDim.x + threadIdx.x;
    const int m = blockIdx.y * blockDim.y + threadIdx.y;
    if (k >= K || m >= M) return;
    const float* q = cpar + m * %(npc)d;
    const float u = (float)k / (float)(K - 1);
    const float s = (u - 1.f) * g[0];
    const float dk = g[1], c2 = g[2];
    const float e1 = __expf(dk * s), e2 = __expf(1.7f * dk * s);
    const float inv = 1.f / (1.f + c2);
    float P[3], D[3];
    #pragma unroll
    for (int a = 0; a < 3; ++a) {
        float x1 = q[6 + a] * s + q[a];     x1 -= rintf(x1);
        float x2 = q[9 + a] * s + q[3 + a]; x2 -= rintf(x2);
        float s1, c1, s2, cc2;
        __sincosf(TAU * x1, &s1, &c1);
        __sincosf(TAU * x2, &s2, &cc2);
        const float w1 = TAU * q[6 + a], w2 = TAU * q[9 + a];
        const float amp = g[3 + a] * q[12] * inv;
        P[a] = amp * (e1 * s1 + c2 * e2 * s2);
        D[a] = amp * (e1 * (dk * s1 + w1 * c1) + c2 * e2 * (1.7f * dk * s2 + w2 * cc2));
    }
    const float3 p = make_float3(P[0], P[1], P[2]);
    // weight: curve fade x tail ramp x head boost
    const float tail = g[12] + (1.f - g[12]) * __powf(u, 1.4f);
    const float boost = 1.f + g[11] * __expf(-(1.f - u) * g[13]);
    const float w = q[13] * tail * boost;
    const int i = m * K + k;
    C[i] = make_float4(p.x, p.y, p.z, w);
    IDX[i] = q[14] + g[14] * u;
    // ribbon frame: camera-facing normal, twisted about the tangent
    float3 T = make_float3(D[0], D[1], D[2]);
    const float tl = h_len(T);
    T = tl > 1e-6f ? make_float3(T.x / tl, T.y / tl, T.z / tl) : make_float3(1.f, 0.f, 0.f);
    float3 V = make_float3(g[7] - p.x, g[8] - p.y, g[9] - p.z);
    const float vl = h_len(V);
    V = make_float3(V.x / (vl + 1e-6f), V.y / (vl + 1e-6f), V.z / (vl + 1e-6f));
    float3 n0 = h_cross(T, V);
    float nl = h_len(n0);
    if (nl < 1e-3f) { n0 = h_cross(T, make_float3(0.f, 1.f, 0.f)); nl = h_len(n0); }
    if (nl < 1e-3f) { n0 = h_cross(T, make_float3(1.f, 0.f, 0.f)); nl = h_len(n0); }
    n0 = make_float3(n0.x / (nl + 1e-9f), n0.y / (nl + 1e-9f), n0.z / (nl + 1e-9f));
    const float3 b0 = h_cross(T, n0);
    float ang = g[10] * s + q[15]; ang -= rintf(ang);
    float sa, ca;
    __sincosf(TAU * ang, &sa, &ca);
    const float hw = g[6] * q[12] * (0.25f + 0.75f * __powf(u, 0.7f)) * (0.35f + 0.65f * e1);
    const float3 n = make_float3((n0.x * ca + b0.x * sa) * hw, (n0.y * ca + b0.y * sa) * hw,
                                 (n0.z * ca + b0.z * sa) * hw);
    RA[i] = make_float4(p.x - n.x, p.y - n.y, p.z - n.z, w);
    RB[i] = make_float4(p.x + n.x, p.y + n.y, p.z + n.z, w);
    if (k == K - 1) {
        HEAD[m] = make_float4(p.x, p.y, p.z, q[13]);
        HIDX[m] = q[14] + g[14];
    }
}
""" % {"npc": NPC}


def _pal_host(coeffs, t: float) -> tuple[float, float, float]:
    """Cosine palette on the host (sRGB 0..1), for the background tint."""
    a, b, c, d = coeffs[0:3], coeffs[3:6], coeffs[6:9], coeffs[9:12]
    return tuple(min(max(a[i] + b[i] * math.cos(2 * math.pi * (c[i] * t + d[i])), 0.0), 1.0) for i in range(3))


def _smooth(e0: float, e1: float, x: float) -> float:
    t = min(max((x - e0) / (e1 - e0), 0.0), 1.0)
    return t * t * (3.0 - 2.0 * t)


class Harmonograph3d(Source):
    name = "harmonograph_3d"
    label = "Harmonograph"
    description = "Glowing 3D harmonograph curves traced by comet heads, woven like a laser sculpture."
    params = {
        **standard_scene_params(palette="neon", render_scale=0.5, period=1.0, drift=0.03),
        "ratio_set": num(0.0, 1.0, 0.5, "Ratio set (3:2:1 .. 5:4:3)", tier="regional", basic=True),
        "curve_count": num(1.0, 8.0, 5.0, "Curves", tier="regional", basic=True),
        "damping": num(0.0, 1.0, 0.35, "Damping (tail spiral)", tier="regional"),
        "tube_width": num(0.0, 0.14, 0.05, "Tube width", tier="regional"),
        "twist": num(0.0, 1.0, 0.35, "Ribbon twist", tier="regional"),
        "complexity": num(0.0, 0.8, 0.3, "Second pendulum", tier="regional"),
        "trail": num(0.2, 1.6, 0.85, "Trail length", tier="regional"),
        "rotation": num(0.0, 2.0, 1.0, "Rotation", unit="×", tier="regional"),
    }

    def setup(self, ctx, params: dict) -> None:
        super().setup(ctx, params)
        cp = ctx.cp
        seed = int(params["seed"])
        rng = np.random.default_rng(seed)
        self.w, self.h = internal_size(ctx, float(params["render_scale"]))
        self.sp = Splat3D(ctx, self.w, self.h, max_points=1024, max_lines=4096, pool=1 << 21)
        self.k_gen = raw_module(_SRC, ("--std=c++14", "--use_fast_math")).get_function("harmo_gen")
        f32 = cp.float32
        self.C = cp.zeros((M_MAX, K, 4), f32)
        self.RA = cp.zeros((M_MAX, K, 4), f32)
        self.RB = cp.zeros((M_MAX, K, 4), f32)
        self.IDX = cp.zeros(M_MAX * K, f32)
        self.HEAD = cp.zeros((M_MAX, 4), f32)
        self.HIDX = cp.zeros(M_MAX, f32)
        self.cpar_h = np.zeros(M_MAX * NPC, np.float32)
        self.g_h = np.zeros(NG, np.float32)
        self.cpar = cp.zeros(M_MAX * NPC, f32)
        self.g = cp.zeros(NG, f32)

        # per-curve constants: nested scales, phase offsets (weave), detune directions (precession)
        c = np.arange(M_MAX, dtype=np.float64)
        self.scale_c = 1.0 - 0.068 * c
        base1 = np.array([0.0, 0.25, 0.11])
        base2 = np.array([0.37, 0.05, 0.62])
        off = np.array([0.043, 0.071, 0.029])
        self.phi1 = (base1[None, :] + c[:, None] * off[None, :] + rng.uniform(-0.02, 0.02, (M_MAX, 3))) % 1.0
        self.phi2 = (base2[None, :] - c[:, None] * off[None, ::-1] + rng.uniform(-0.02, 0.02, (M_MAX, 3))) % 1.0
        axis_dir = np.array([1.0, -0.6, 0.45])
        self.dv1 = axis_dir[None, :] * (1.0 + 0.18 * c[:, None]) + rng.uniform(-0.35, 0.35, (M_MAX, 3))
        self.dv2 = -0.7 * axis_dir[None, ::-1] + rng.uniform(-0.5, 0.5, (M_MAX, 3))
        self.pal_off = (0.13 * c + rng.uniform(-0.02, 0.02, M_MAX))
        self.twist_ph = np.zeros(M_MAX)

        self.rot = float(rng.uniform(0.0, 6.28))   # sculpture yaw (host float64)
        self.wob = 0.0                            # sculpture tilt wobble phase (cycles)
        self.yaw = 0.0                            # camera orbit
        self.bob = 0.0                            # camera bob phase (cycles)
        self.det = 0.0                            # frequency-detune wobble phase (cycles)
        self.drift = 0.0
        self.e_s = None

    def render(self, t_local: float, dt: float, out) -> None:
        p = self.step_params(dt)
        e = min(max(float(p["energy"]), 0.0), 1.0)
        pulse = min(max(float(p["pulse"]), 0.0), 1.0)
        spd = float(p["speed"])
        dt = min(max(float(dt), 0.0), 0.1)
        a = 1.0 - math.exp(-dt / 0.35) if dt > 0 else 1.0
        self.e_s = e if self.e_s is None else self.e_s + (e - self.e_s) * a
        es = self.e_s

        # ---- frequencies: ratio table morph (short dwell on each pure figure) + slow detune wobble
        rs = min(max(float(p["ratio_set"]), 0.0), 1.0) * (len(RATIOS) - 1)
        i0 = min(int(math.floor(rs)), len(RATIOS) - 2)
        fr = _smooth(0.15, 0.85, rs - i0)
        f1 = RATIOS[i0] * (1.0 - fr) + RATIOS[i0 + 1] * fr
        self.det = (self.det + spd * (0.025 + 0.05 * e) * dt) % 1.0
        dep = 0.006 + 0.018 * es
        f1 = f1 + dep * np.sin(2 * math.pi * (self.det + np.array([0.0, 1 / 3, 2 / 3])))
        f2 = np.roll(f1, -1)

        # ---- host-integrated phases (wrapped): trace slides the curve along itself; detune precesses it
        trace = spd * (0.03 + 0.11 * e)
        detr = spd * (0.008 + 0.04 * e)
        self.phi1 = (self.phi1 + (f1[None, :] * trace + self.dv1 * detr) * dt) % 1.0
        self.phi2 = (self.phi2 + (f2[None, :] * trace + self.dv2 * detr) * dt) % 1.0
        tw = float(p["twist"])
        self.twist_ph = (self.twist_ph + spd * tw * (0.05 + 0.1 * e) * (1.0 + 0.15 * np.arange(M_MAX)) * dt) % 1.0
        self.rot += spd * float(p["rotation"]) * (0.04 + 0.16 * e) * dt
        self.wob = (self.wob + spd * (0.013 + 0.02 * e) * dt) % 1.0
        self.yaw += spd * (0.012 + 0.04 * e) * dt
        self.bob = (self.bob + spd * (0.03 + 0.04 * e) * dt) % 1.0
        self.drift = math.fmod(self.drift + float(p["drift_speed"]) * spd * dt, 1000.0)

        # ---- curve-count weights (continuous fade; energy adds curves)
        n_eff = 1.0 + (float(p["curve_count"]) - 1.0) * (0.45 + 0.55 * es)
        weights = np.clip(n_eff - np.arange(M_MAX), 0.0, 1.0)
        n_act = max(1, min(M_MAX, int(math.ceil(n_eff - 1e-4))))

        # ---- model (sculpture rotation) and camera
        R = mat_euler(0.28 * math.sin(2 * math.pi * self.wob), self.rot, 0.12 * math.sin(2 * math.pi * self.wob + 1.3))
        pitch = 0.2 + (0.05 + 0.06 * es) * math.sin(2 * math.pi * self.bob)
        D = CAM_D * (1.0 - 0.025 * math.sin(2 * math.pi * self.bob + 0.7))
        eye = np.array(orbit((0.0, 0.0, 0.0), D, self.yaw, pitch))
        cam = look_at(tuple(eye.tolist()), (0.0, 0.0, 0.0), fov_deg=50.0)
        eye_m = R[:, :3].T @ (eye - R[:, 3])

        # ---- upload params and generate geometry
        cph = self.cpar_h.reshape(M_MAX, NPC)
        cph[:, 0:3] = self.phi1
        cph[:, 3:6] = self.phi2
        cph[:, 6:9] = f1[None, :]
        cph[:, 9:12] = f2[None, :]
        cph[:, 12] = self.scale_c
        cph[:, 13] = weights
        cph[:, 14] = self.pal_off
        cph[:, 15] = self.twist_ph
        g = self.g_h
        span = float(p["trail"])
        g[0] = span
        g[1] = float(p["damping"]) * 3.2
        g[2] = float(p["complexity"])
        g[3:6] = AMP
        g[6] = float(p["tube_width"]) * (1.0 + 0.6 * pulse) * (0.85 + 0.3 * es)
        g[7:10] = eye_m
        g[10] = tw * 6.0
        g[11] = 1.2 + 0.8 * e + 3.0 * pulse
        g[12] = 0.04
        g[13] = 55.0 / max(span, 0.2)
        g[14] = 0.55
        self.cpar.set(self.cpar_h)
        self.g.set(self.g_h)
        launch_2d(self.k_gen, K, n_act, (self.C, self.RA, self.RB, self.IDX, self.HEAD, self.HIDX, self.cpar,
                                          self.g, np.int32(K), np.int32(n_act)))

        # ---- draw
        sp = self.sp
        sp.clear()
        sess = self.session_palette()
        coeffs = np.asarray(PALETTES[p["palette"]] if sess is None else sess, np.float64).reshape(-1)
        pal = tuple(coeffs.tolist())
        period, drift = float(p["palette_period"]), self.drift
        far = (D - 0.5, D + 2.3)
        gain = (0.7 + 0.55 * e) * (1.0 + 0.4 * pulse)
        model = R

        if float(p["tube_width"]) > 1e-4:
            sp.ribbons(self.RA, self.RB, strands=6, k=K, n_ribbons=n_act, edge=2.3, cam=cam, model=model,
                       intensity=0.2 * gain, width_px=1.3 * (1.0 + 0.4 * pulse), weight_in_w=True, palette=pal,
                       index=self.IDX, period=period, drift=drift, far_fade=far)
        sp.polylines(self.C, k=K, n_strips=n_act, cam=cam, model=model, intensity=1.0 * gain,
                     width_px=2.0 * (1.0 + 0.5 * pulse), weight_in_w=True, palette=pal, index=self.IDX,
                     period=period, drift=drift + 0.05, colour=(1.25, 1.25, 1.25), far_fade=far)
        flare = 1.0 + 2.5 * pulse
        sp.points(self.HEAD, n=n_act, cam=cam, model=model, intensity=4.0 * gain * flare, size_px=4.0,
                  weight_in_w=True, palette=pal, index=self.HIDX, period=period, drift=drift + 0.1,
                  colour=(1.5, 1.5, 1.5), far_fade=far)
        sp.points(self.HEAD, n=n_act, cam=cam, model=model, intensity=7.0 * gain * flare,
                  size_px=11.0 * (1.0 + 0.5 * pulse), size_range=(0.6, 16.0), weight_in_w=True, palette=pal,
                  index=self.HIDX, period=period, drift=drift + 0.1, far_fade=far)

        bg = _pal_host(coeffs, drift + 0.5)
        bgk = 0.035
        sp.resolve(out, exposure=1.05 * float(p["intensity"]), tonemap="aces", saturation=1.1,
                   glow=(0.55 + 0.5 * e) * (1.0 + 0.5 * pulse), glow_radius_px=18.0, glow_wide=0.5,
                   background=(bg[0] * bgk, bg[1] * bgk, bg[2] * bgk + 0.008))

    def close(self) -> None:
        if getattr(self, "sp", None) is not None:
            self.sp.close()
        self.sp = None
        self.C = self.RA = self.RB = self.IDX = self.HEAD = self.HIDX = self.cpar = self.g = None
